export const useTranslation = (lang?: string) => {
  const code: AppLanguage = String(lang).toLowerCase() === 'ar' ? 'ar' : 'fr';
  const dict = TRANSLATIONS[code] || TRANSLATIONS.fr;
  return Object.assign({}, dict, {
    t: (
      key: keyof typeof TRANSLATIONS.fr,
      fallbackOrParams?: string | Record<string, string | number>,
      maybeParams?: Record<string, string | number>
    ): string => {
      let text = (TRANSLATIONS[code] as any)?.[key];
      let fallback: string | undefined;
      let params: Record<string, string | number> | undefined;

      if (typeof fallbackOrParams === 'string') {
        fallback = fallbackOrParams;
        params = maybeParams;
      } else if (fallbackOrParams && typeof fallbackOrParams === 'object') {
        params = fallbackOrParams;
      }

      if (!text) {
        text = fallback || (TRANSLATIONS.fr as any)[key] || String(key);
      }

      if (params && typeof text === 'string') {
        for (const [pKey, pVal] of Object.entries(params)) {
          text = text.replace(new RegExp(`\\{${pKey}\\}`, 'g'), String(pVal));
        }
      }

      return text;
    },
    tControlled: (category: keyof typeof CONTROLLED_TRANSLATIONS.fr, codeKey: string): string => {
      const cat = CONTROLLED_TRANSLATIONS[code]?.[category] as Record<string, string> | undefined;
      if (cat && cat[codeKey]) {
        return cat[codeKey];
      }
      const fallbackCat = CONTROLLED_TRANSLATIONS.fr?.[category] as Record<string, string> | undefined;
      if (fallbackCat && fallbackCat[codeKey]) {
        return fallbackCat[codeKey];
      }
      return codeKey;
    },
  });
};
