export const useTranslation = (lang?: string) => {
  const code: AppLanguage = String(lang).toLowerCase() === 'ar' ? 'ar' : 'fr';
  const dict = TRANSLATIONS[code] || TRANSLATIONS.fr;
  return Object.assign({}, dict, {
    t: (key: keyof typeof TRANSLATIONS.fr, fallback?: string): string => {
      const val = (TRANSLATIONS[code] as any)?.[key];
      if (val) return val;
      if (fallback) return fallback;
      return (TRANSLATIONS.fr as any)[key] || String(key);
    },
    tControlled: (category: keyof typeof CONTROLLED_TRANSLATIONS.fr, codeKey: string): string => {
      const cat = CONTROLLED_TRANSLATIONS[code]?.[category] as Record<string, string> | undefined;
      if (cat && cat[codeKey]) {
        return cat[codeKey];
      }
      const fallbackCat = CONTROLLED_TRANSLATIONS.fr?.[category] as Record<string, string> | undefined;
      if (fallbackCat && fallbackCat[codeKey]) {
        return fallbackCat[codeKey];
      }
      return codeKey;
    },
  });
};
